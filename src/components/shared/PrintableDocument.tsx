import * as React from "react";
import { Printer, Download } from "lucide-react";
import { Button } from "@/components/ui/button";
import { formatDate } from "@/lib/utils";

export interface PrintableDocumentProps {
  title: string;
  documentNumber?: string;
  date?: string;
  author?: string;
  status?: string;
  children: React.ReactNode;
  onDownloadPdf?: () => void;
}

export function PrintableDocument({
  title,
  documentNumber = "DOC-2024-001",
  date = new Date().toISOString(),
  author = "System Administrator",
  status = "Official",
  children,
  onDownloadPdf,
}: PrintableDocumentProps) {
  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-4">
      {/* Actions (hidden in print) */}
      <div className="flex justify-end gap-2 print:hidden">
        <Button variant="outline" size="sm" onClick={handlePrint} className="gap-1.5">
          <Printer className="h-4 w-4" />
          Print Document
        </Button>
        {onDownloadPdf && (
          <Button variant="outline" size="sm" onClick={onDownloadPdf} className="gap-1.5">
            <Download className="h-4 w-4" />
            Download PDF
          </Button>
        )}
      </div>

      {/* Printable Sheet */}
      <div className="mx-auto max-w-3xl rounded-xl border bg-card p-8 shadow-sm text-card-foreground print:border-0 print:shadow-none print:p-0 print:m-0">
        {/* Document Header */}
        <div className="flex items-start justify-between border-b pb-6">
          <div>
            <div className="flex items-center gap-2">
              <span className="h-7 w-7 rounded-lg bg-primary text-primary-foreground font-bold flex items-center justify-center text-sm">
                A
              </span>
              <span className="font-bold text-lg text-foreground">AppTemplate</span>
            </div>
            <h1 className="mt-4 text-2xl font-bold tracking-tight text-foreground">
              {title}
            </h1>
          </div>
          <div className="text-right text-xs text-muted-foreground space-y-1">
            <p>
              <strong className="text-foreground">Doc Ref:</strong> {documentNumber}
            </p>
            <p>
              <strong className="text-foreground">Date:</strong> {formatDate(date)}
            </p>
            <p>
              <strong className="text-foreground">Status:</strong> {status}
            </p>
          </div>
        </div>

        {/* Content Body */}
        <div className="py-6 text-sm leading-relaxed">{children}</div>

        {/* Document Footer */}
        <div className="mt-8 border-t pt-6 text-xs text-muted-foreground flex justify-between items-center">
          <p>Generated by AppTemplate &bull; Confidential</p>
          <p>Approved by: {author}</p>
        </div>
      </div>
    </div>
  );
}
